// UCS-1158 — the derived layer: plural browse trees, synthesized call numbers,
// a resolution index. Regenerable, disposable, and load-bearing for nothing.
//
// Tested through its public seam: the CLI process — exit codes and output ARE
// the contract. The assertions are golden-file style in this repo's idiom: full
// stable-sorted projections compared against literal expectations, which works
// only because the output carries no timestamps and stable-sorts everything.
//
// The five acceptance criteria map onto the sections below:
//   1  two axes from one flat store, stable-sorted        -> 'plural axes'
//   2  call numbers are display strings, never identity   -> 'call numbers'
//   3  delete + regenerate is byte-identical              -> 'round trip'
//   4  stale and draft leaves visibly demoted, not hidden -> 'demotion'
//   5  embedding recall has a slot and a gate, no impl    -> 'recall slot'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { chmodSync, cpSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { AXES } from '../payload/engine/lib/derived.js';
import { ID_GRAMMARS, idPattern } from '../payload/engine/lib/id-grammars.js';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const cli = join(repoRoot, 'payload', 'engine', 'derive.js');
const fixture = (name) => join(repoRoot, 'tests', 'fixtures', 'derived', name);

/** The injected date every test measures staleness against. Never the clock. */
const TODAY = '2026-08-16';

/** A writable copy of a fixture store — the derived layer is written into it. */
function scratch(t, name = 'store') {
  const dir = mkdtempSync(join(tmpdir(), 'uk-derived-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  cpSync(fixture(name), dir, { recursive: true });
  return dir;
}

function derive(root, args = []) {
  const r = spawnSync(process.execPath, [cli, '--root', root, ...args], { encoding: 'utf8' });
  return { ...r, json: r.stdout.startsWith('{') ? JSON.parse(r.stdout) : null };
}

const derivedFile = (root, name) => readFileSync(join(root, 'knowledge', 'derived', name), 'utf8');

/** Every file under the derived directory, relative and forward-slashed. */
function derivedFiles(root) {
  return readdirSync(join(root, 'knowledge', 'derived'), { recursive: true })
    .map(String)
    .sort();
}

// ------------------------------------------------------------- 1 · plural axes

test('generation produces browse trees along two axes from one flat store', (t) => {
  const root = scratch(t);
  const r = derive(root, ['--today', TODAY, '--write', '--json']);
  assert.equal(r.status, 0, r.stderr);

  // Plural, and named by the axis table rather than by this test — a third axis
  // is a row in AXES, and this assertion follows it there.
  assert.deepEqual(
    r.json.artifacts,
    ['knowledge/derived/index.json', ...AXES.map((a) => `knowledge/derived/tree.${a.key}.md`)].sort(),
  );
  assert.deepEqual(AXES.map((a) => a.key), ['domain-form', 'form-domain'],
    'the two shipped axes are domain-first for stewards and form-first for agents');

  // The SAME leaves, projected two ways: one flat store, two orderings. The
  // domain-first tree opens on a domain node, the form-first one on a form.
  const domainFirst = derivedFile(root, 'tree.domain-form.md');
  const formFirst = derivedFile(root, 'tree.form-domain.md');
  assert.match(domainFirst, /^- \*\*design-system\/\*\* \(3\)$/m);
  assert.match(formFirst, /^- \*\*constraint\/\*\* \(3\)$/m);
  assert.notEqual(domainFirst, formFirst, 'two axes are two trees, not one tree twice');

  // Every leaf appears in BOTH trees — a projection reorders the store, it
  // never selects from it.
  for (const id of ['L-000117', 'L-000133', 'L-000162', 'L-000171', 'L-000213', 'L-000228']) {
    assert.ok(domainFirst.includes(id), `${id} is missing from the domain-first tree`);
    assert.ok(formFirst.includes(id), `${id} is missing from the form-first tree`);
  }
});

